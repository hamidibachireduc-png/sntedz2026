// Helper functions for easy querying across components
export const getAllHierarchyStructures = (): HierarchyStructure[] => {
  const result: HierarchyStructure[] = [];
  UNION_HIERARCHY_LEVELS.forEach((level) => {
    result.push(...level.structures);
  });
  return result;
};

export const getHierarchyStructureById = (id: string): HierarchyStructure | undefined => {
  return getAllHierarchyStructures().find((s) => s.id === id);
};

export const getStructuresByLevel = (levelKey: HierarchyLevelKey): HierarchyStructure[] => {
  const lvl = UNION_HIERARCHY_LEVELS.find((l) => l.key === levelKey);
  return lvl ? lvl.structures : [];
};

