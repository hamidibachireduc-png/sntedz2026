export const initWilayasList = () => {
  try {
    if (typeof window === "undefined") return;

    // 1. مزامنة قاعدة الحسابات المحلية إن كانت فارغة أو تحديثها بالبيانات الرسمية للشيت
    const existingAccountsRaw = localStorage.getItem("snte_accounts_v3");
    if (!existingAccountsRaw || JSON.parse(existingAccountsRaw).length === 0) {
      localStorage.setItem("snte_accounts_v3", JSON.stringify(OFFICIAL_UNION_STRUCTURES));
    }

    const cached = localStorage.getItem("snte_structures_db");
    if (cached) {
      const parsed = JSON.parse(cached);
      const cachedAccounts = parsed.accounts || [];
      if (cachedAccounts.length > 0) {
        UNION_ACCOUNTS.length = 0;
        UNION_ACCOUNTS.push(...cachedAccounts);
      }

      const cachedWilayas = parsed.wilayas || [];
      cachedWilayas.forEach((cw: any) => {
        const existing = WILAYAS_LIST.find(w => String(w.code) === String(cw.code));
        if (existing) {
          if (cw.sgName) existing.sgName = cw.sgName;
          if (cw.phone) existing.phone = cw.phone;
          if (cw.email) existing.email = cw.email;
          if (cw.status) existing.status = cw.status;
          if (cw.username) existing.username = cw.username;
          if (cw.password) existing.password = cw.password;
        }
      });
    }
  } catch (e) {
    console.error("خطأ في قراءة الذاكرة المحلية", e);
  }
};

initWilayasList();
