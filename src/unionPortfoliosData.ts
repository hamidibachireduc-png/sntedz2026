export function getTaskByRoleName(roleName: string): SyndicateTaskItem | null {
  if (!roleName) return null;
  const clean = roleName.trim();
  const foundKey = Object.keys(SNTE_LAW_TASKS).find(
    (k) => clean.includes(k) || k.includes(clean)
  );
  return foundKey ? SNTE_LAW_TASKS[foundKey] : null;
}